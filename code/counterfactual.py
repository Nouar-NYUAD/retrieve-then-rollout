"""Counterfactual (interventional) evaluation of in-context world models.

Question  Does the world model predict what happens under an action the data-collecting policy did
          NOT take?  Planning queries exactly these counterfactuals (CEM evaluates many candidate
          actions from the same state), but offline accuracy is measured on the logged actions only.
          In single-policy data (D4RL "medium") the action is largely a function of the state, so a
          model can fit the logged transitions while ignoring - or mis-estimating - the action effect.

Ground truth
  hopper / halfcheetah / walker2d : Gymnasium MuJoCo v5 simulator, state set from the D4RL
          observation (qpos = [0, obs[:nq-1]], qvel = obs[nq-1:]); the root x position is not
          observed and does not enter the dynamics. Hopper / Walker2d observations clip qvel to
          [-10, 10]; query states with a clipped velocity are skipped (state not recoverable).
          A sim-vs-D4RL consistency check of the logged transitions is stored in the output.
  pendulum : the known equations (pilot.pendulum_f, RK4, dt 0.05). Pool data are generated by a
          feedback controller u = gain * (-3 sin(theta) - omega) + sigma * eps; sigma (exploration)
          is varied with everything else fixed -> controlled confounding experiment
          (gain 0, sigma 1 = the random-excitation data of the main study).

Queries   For a query state s with logged action a: the factual action a, plus K counterfactual
          actions at each level  sigma_k in {0.1, 0.3, 1.0} x (pool action sd), a' = clip(a + noise),
          and "uniform" (uniform over the pool action range). Actions are clipped to the range seen
          in the pool, so counterfactuals test action effects, not action extrapolation.

Metrics (state changes in units of the pool state sd)
  factual_err      RMS error of the predicted change for the logged action.
  cf_err[level]    RMS error of the predicted change for the counterfactual actions.
  effect_rel[level] ||e_hat - e|| / ||e||, e = Delta(s,a') - Delta(s,a): error of the predicted
                   EFFECT of switching action. 1 = as good as an action-blind model (e_hat = 0).
  effect_cos[level] cosine between e_hat and e.
  rank_rho[level]  Spearman correlation, over the factual + K actions, between predicted and true
                   next forward velocity (pendulum: next angular velocity) - does the model order
                   candidate actions as the planner needs?
  multi-step (h steps, a few states): open-loop rollouts of perturbed action sequences; error of
                   the predicted final-state effect relative to the factual sequence.
  confounding      R^2 of predicting the action from the state in the pool (10-NN, held-out half).

Context strategies (H = 100 rows unless stated)
  retrieval        nearest pool rows to the QUERY (state, action) - the paper's method; a new
                   context per counterfactual query.
  retrieval_state  nearest rows by state only (one context shared by all actions of a state).
  retrieval_div    action-diverse retrieval: 5H nearest by state, then H chosen by farthest-point
                   sampling in (standardised) action space - proposed fix.
  recent / random / full (cap 5000) / trained (MLP, global) - as in study.py.
  --explore_frac f adds f x |pool| exploratory transitions (uniform random actions applied at
                   random pool states, one step, from the simulator) - second proposed fix.
"""
import argparse
import json
import time
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

import pilot as P
import study as S

CODE_VERSION = "2026-11-15cf2"   # cf2: low-memory TabPFN path (same predictions), --multi_arms
ENVS = {"halfcheetah": "HalfCheetah-v5", "hopper": "Hopper-v5", "walker2d": "Walker2d-v5"}
VX = {"halfcheetah": 8, "hopper": 5, "walker2d": 8, "pendulum": 1}   # forward-velocity obs index
CLIPPED_QVEL = {"hopper", "walker2d"}
LEVELS = ["0.1", "0.3", "1.0", "uniform"]


class LowMemPredictor(S.Predictor):
    """study.Predictor with a low-memory TabPFN path: per state dimension the regressor is fitted,
    used and freed before the next one (study.Predictor keeps all d fitted regressors, ~1 GB of GPU
    memory each, alive to reuse a fixed context; 17 dims x several processes exhausted an 80 GB GPU).
    Same model, seed and data as P.make_model("tabpfn") -> identical predictions (regtest)."""
    def __call__(self, model, idx, Xq):
        if model != "tabpfn":
            return super().__call__(model, idx, Xq)
        Xc, Yc = self.pool.X[idx], self.pool.Y[idx]
        out = np.empty((len(Xq), Yc.shape[1]))
        for j in range(Yc.shape[1]):
            m = P.make_model("tabpfn", self.args, self.seed).fit(Xc, Yc[:, j])
            out[:, j] = m.predict(Xq)
            del m
        return out


# ----------------------------------------------------------------------------- ground truth
class Truth:
    def __init__(self, system):
        self.system = system
        if system in ENVS:
            import gymnasium as gym
            self.e = gym.make(ENVS[system]).unwrapped
            self.e.reset(seed=0)
            self.nq = self.e.model.nq

    def ok(self, s):
        if self.system in CLIPPED_QVEL:
            return bool(np.all(np.abs(s[self.nq - 1:]) < 10 - 1e-6))
        return True

    def _set(self, s):
        self.e.set_state(np.concatenate([[0.0], s[:self.nq - 1]]), s[self.nq - 1:].copy())

    def step(self, s, A):
        """next states for each action in A from the same state s: (len(A), d)"""
        if self.system == "pendulum":
            return np.stack([P.rk4(P.pendulum_f, s, a, P.SYSTEMS["pendulum"]["dt"]) for a in A])
        out = []
        for a in A:
            self._set(s); o, *_ = self.e.step(np.asarray(a, dtype=float)); out.append(o)
        return np.array(out, dtype=float)

    def rollout(self, s, Aseq):
        """states after each action of the sequence: (len(Aseq), d)"""
        if self.system == "pendulum":
            out, x = [], s.copy()
            for a in Aseq:
                x = P.rk4(P.pendulum_f, x, a, P.SYSTEMS["pendulum"]["dt"]); out.append(x)
            return np.array(out)
        self._set(s); out = []
        for a in Aseq:
            o, *_ = self.e.step(np.asarray(a, dtype=float)); out.append(o)
        return np.array(out, dtype=float)


# ----------------------------------------------------------------------------- data
def pendulum_episode(T, rng, gain, sigma):
    dt = P.SYSTEMS["pendulum"]["dt"]
    x = np.array([rng.uniform(-np.pi, np.pi), rng.normal(0, 1)])
    Sx, U = [x], []
    for _ in range(T):
        u = np.array([gain * (-3.0 * np.sin(x[0]) - x[1]) + sigma * rng.normal()])
        x = P.rk4(P.pendulum_f, x, u, dt); Sx.append(x); U.append(u)
    return np.array(Sx), np.array(U)


def seed_data(args, rng):
    """pool transitions (training episodes), held-out test episode (states T+1, actions T), state sd"""
    if args.system in S.D4RL:
        a = argparse.Namespace(**vars(args)); a.lags = 1
        Xtr, Ytr, S_te, _, U_te, sd = S.d4rl_seed(a, rng)
        return Xtr, Ytr, S_te, U_te, sd
    eps = [pendulum_episode(args.T_train, rng, args.gain, args.sigma) for _ in range(args.n_train)]
    S_te, U_te = pendulum_episode(args.T_test, rng, args.gain, args.sigma)
    Xs, Ys = zip(*[P.transitions(Sx, U) for Sx, U in eps])
    sd = np.vstack([Sx for Sx, _ in eps]).std(0) + 1e-8
    return np.vstack(Xs), np.vstack(Ys), S_te, U_te, sd


def confounding_r2(X, d, rng):
    """R^2 of predicting the action from the state (10-NN on standardised states, held-out half)"""
    n = len(X); perm = rng.permutation(n); tr, te = perm[: n // 2], perm[n // 2:]
    Zs = (X[:, :d] - X[:, :d].mean(0)) / (X[:, :d].std(0) + 1e-12)
    A = X[:, d:]
    te = te[:2000]
    pred = []
    for i in te:
        nn = np.argpartition(((Zs[tr] - Zs[i]) ** 2).sum(1), 9)[:10]
        pred.append(A[tr][nn].mean(0))
    pred = np.array(pred)
    return float(np.mean(1 - ((pred - A[te]) ** 2).sum(0) / (((A[te] - A[te].mean(0)) ** 2).sum(0) + 1e-12)))


# ----------------------------------------------------------------------------- contexts
class Contexts:
    """Context row indices for a query (s, a). Shared strategies return the SAME index object for
    the same state so study.Predictor reuses its fitted per-dimension models."""
    def __init__(self, pool, d, H, hist_idx, rng, full_cap):
        self.pool, self.d, self.H, self.hist_idx, self.rng = pool, d, H, hist_idx, rng
        self.Zs = pool.Z[:, :d]; self.Za = pool.Z[:, d:]
        self.fixed = {"recent": hist_idx[-H:],
                      "random": pool.random(H, rng),
                      "full": P.select("full", pool, H, hist_idx, None, rng, full_cap)}
        self.cache = {}

    def _state_nearest(self, s, n):
        z = (s - self.pool.mu[:self.d]) / self.pool.sd[:self.d]
        d2 = ((self.Zs - z) ** 2).sum(1); n = min(n, len(d2))
        return np.argpartition(d2, n - 1)[:n], d2

    def get(self, strategy, s, a):
        if strategy in self.fixed:
            return self.fixed[strategy]
        if strategy == "retrieval":
            return self.pool.nearest(self.H, np.concatenate([s, a]))
        key = (strategy, s.tobytes())
        if key in self.cache:
            return self.cache[key]
        if strategy == "retrieval_state":
            idx, _ = self._state_nearest(s, self.H)
        elif strategy == "retrieval_div":
            cand, d2 = self._state_nearest(s, 5 * self.H)
            Za = self.Za[cand]
            chosen = [int(np.argmin(d2[cand]))]
            mind = ((Za - Za[chosen[0]]) ** 2).sum(1)
            for _ in range(min(self.H, len(cand)) - 1):
                j = int(np.argmax(mind)); chosen.append(j)
                mind = np.minimum(mind, ((Za - Za[j]) ** 2).sum(1))
            idx = cand[np.array(chosen)]
        else:
            raise ValueError(strategy)
        self.cache = {key: idx}            # one state at a time: keep the cache tiny
        return idx


def predict(pred, ctx, strategy, model, Sq, Aq):
    """predicted state changes for queries (Sq[i], Aq[i]); rows sharing a context are batched"""
    Xq = np.hstack([Sq, Aq])
    if strategy == "trained":
        return pred(model, None, Xq)
    out = np.empty((len(Xq), Sq.shape[1])); groups = {}
    for i in range(len(Xq)):
        idx = ctx.get(strategy, Sq[i], Aq[i])
        groups.setdefault(id(idx), (idx, []))[1].append(i)
    for idx, rows in groups.values():
        out[rows] = pred(model, idx, Xq[rows])
    return out


ARMS = {  # strategy -> models
    "retrieval": ["tabpfn", "dynapfn", "locallin"],
    "retrieval_state": ["tabpfn", "dynapfn", "locallin"],
    "retrieval_div": ["tabpfn", "dynapfn", "locallin"],
    "recent": ["tabpfn", "dynapfn"],
    "random": ["tabpfn"],
    "full": ["tabpfn", "locallin"],
    "trained": ["mlp"],
}


# ----------------------------------------------------------------------------- experiment
def counterfactual_actions(a, a_sd, lo, hi, K, rng):
    acts = {}
    for lev in LEVELS:
        if lev == "uniform":
            A = rng.uniform(lo, hi, (K, len(a)))
        else:
            A = a + float(lev) * a_sd * rng.normal(size=(K, len(a)))
        acts[lev] = np.clip(A, lo, hi)
    return acts


def metrics(D0_hat, D0, Dk_hat, Dk, sd, vx):
    """one state: D0 (d,) factual change, Dk (K, d) counterfactual changes; *_hat predicted"""
    e, e_hat = (Dk - D0) / sd, (Dk_hat - D0_hat) / sd
    rel = float(np.sqrt(((e_hat - e) ** 2).sum() / ((e ** 2).sum() + 1e-12)))
    cos = float((e_hat * e).sum() / (np.linalg.norm(e_hat) * np.linalg.norm(e) + 1e-12))
    v_true = np.concatenate([[D0[vx]], Dk[:, vx]]); v_hat = np.concatenate([[D0_hat[vx]], Dk_hat[:, vx]])
    flat = lambda v: np.ptp(v) <= 1e-9 * (np.abs(v).max() + 1e-12)       # constant up to round-off
    rho = 0.0 if flat(v_hat) or flat(v_true) else spearmanr(v_hat, v_true).statistic   # no ranking = 0
    return dict(cf_err=float(np.sqrt(np.mean(((Dk_hat - Dk) / sd) ** 2))), effect_rel=rel,
                effect_cos=cos, rank_rho=float(rho))


def run(args):
    truth = Truth(args.system)
    mods = argparse.Namespace(target="delta", tabpfn_version=args.tabpfn_version, tabpfn_n_estimators=0,
                              dynapfn_degree=2 if args.system in ENVS else 4, gp_fit_n=500, gp_restarts=5, tabpfn_fit_mode=None)
    vx = VX[args.system]
    out = dict(args=vars(args), code_version=CODE_VERSION, seeds={}, results=[])
    for seed in args.seed_ids:
        rng = np.random.default_rng(1000 * seed + 7)         # same pool / test episode as study.py
        Xtr, Ytr, S_te, U_te, sd = seed_data(args, rng)
        d = S_te.shape[1]
        crng = np.random.default_rng(seed * 7919 + 11)
        if args.explore_frac > 0:                               # fix 2: small exploratory dataset
            n_exp = int(args.explore_frac * len(Xtr))
            lo0, hi0 = Xtr[:, d:].min(0), Xtr[:, d:].max(0)
            Xe, Ye = [], []
            for i in crng.choice(len(Xtr), n_exp, replace=False):
                s = Xtr[i, :d]
                if not truth.ok(s):
                    continue
                a = crng.uniform(lo0, hi0)
                Xe.append(np.concatenate([s, a])); Ye.append(truth.step(s, a[None])[0] - s)
            Xtr, Ytr = np.vstack([Xtr, Xe]), np.vstack([Ytr, Ye])
        # sim consistency on logged pool transitions (D4RL); pendulum is exact by construction
        chk = crng.choice(len(Xtr), min(200, len(Xtr)), replace=False)
        cons = [np.abs(truth.step(Xtr[i, :d], Xtr[i, d:][None])[0] - Xtr[i, :d] - Ytr[i]) / sd
                for i in chk if truth.ok(Xtr[i, :d])]
        cons_med = float(np.median(cons))
        conf = confounding_r2(Xtr, d, crng)
        a_sd = Xtr[:, d:].std(0); lo, hi = Xtr[:, d:].min(0), Xtr[:, d:].max(0)
        print(f"[{args.system} s{seed}] pool {len(Xtr)} rows; sim-vs-data median {cons_med:.3e}; "
              f"action-from-state R2 {conf:.3f}", flush=True)
        assert cons_med < 0.05, "simulator does not reproduce the pool transitions - check state mapping"
        out["seeds"][str(seed)] = dict(pool_rows=len(Xtr), sim_consistency_median=cons_med,
                                      action_from_state_r2=conf)
        mlp = S.train_mlp(Xtr, Ytr, seed)

        T = len(U_te)
        cand = [t for t in range(args.t_min, T - args.h_multi - 1) if truth.ok(S_te[t])]
        times = np.array(cand)[np.linspace(0, len(cand) - 1, args.n_states).astype(int)]
        roll_times = set(times[np.linspace(0, len(times) - 1, args.n_roll_states).astype(int)].tolist())
        skipped = (T - args.h_multi - 1 - args.t_min) - len(cand)
        for t in times:
            s, a = S_te[t].astype(float), U_te[t].astype(float)
            X_te, Y_te = P.transitions(S_te[: t + 1], U_te[:t])      # test-episode history before t
            pool = P.Pool(np.vstack([Xtr, X_te]), np.vstack([Ytr, Y_te]))
            hist_idx = np.arange(len(Xtr), len(pool.X))
            prng = np.random.default_rng(seed * 104729 + int(t))
            ctx = Contexts(pool, d, args.H, hist_idx, prng, args.full_cap)
            pred = LowMemPredictor(mods, seed, pool, prng); pred.mlp = mlp
            acts = counterfactual_actions(a, a_sd, lo, hi, args.K, np.random.default_rng(seed * 31 + int(t)))
            A_all = np.vstack([a[None]] + [acts[l] for l in LEVELS])
            D_true = truth.step(s, A_all) - s
            # multi-step sequences: factual logged actions + one perturbed sequence per level
            seqs = None
            if int(t) in roll_times:
                srng = np.random.default_rng(seed * 61 + int(t))
                base = U_te[t:t + args.h_multi].astype(float)
                seqs = {"factual": base}
                for lev in LEVELS:
                    seqs[lev] = np.clip(srng.uniform(lo, hi, base.shape) if lev == "uniform" else
                                        base + float(lev) * a_sd * srng.normal(size=base.shape), lo, hi)
                roll_true = {k: truth.rollout(s, v) for k, v in seqs.items()}
            for strategy, models in ARMS.items():
                for model in models:
                    if model not in args.models:
                        continue
                    tic = time.time()
                    D_hat = predict(pred, ctx, strategy, model, np.repeat(s[None], len(A_all), 0), A_all)
                    r = dict(system=args.system, seed=seed, t=int(t), strategy=strategy, model=model,
                             H=args.H, explore_frac=args.explore_frac, gain=args.gain, sigma=args.sigma,
                             code_version=CODE_VERSION,
                             factual_err=float(np.sqrt(np.mean(((D_hat[0] - D_true[0]) / sd) ** 2))))
                    k0 = 1
                    for lev in LEVELS:
                        sl = slice(k0, k0 + args.K); k0 += args.K
                        r[lev] = metrics(D_hat[0], D_true[0], D_hat[sl], D_true[sl], sd, vx)
                    r["all"] = metrics(D_hat[0], D_true[0], D_hat[1:], D_true[1:], sd, vx)
                    if seqs is not None and f"{model}:{strategy}" in args.multi_arms:
                        names = list(seqs); x = np.repeat(s[None], len(names), 0); fin = {}
                        for h in range(args.h_multi):
                            Ah = np.stack([seqs[k][h] for k in names])
                            x = x + predict(pred, ctx, strategy, model, x, Ah)
                            x[~np.all(np.isfinite(x), 1)] = np.nan
                        for i, k in enumerate(names):
                            fin[k] = x[i]
                        mr = {}
                        for lev in LEVELS:
                            e = (roll_true[lev][-1] - roll_true["factual"][-1]) / sd
                            e_hat = (fin[lev] - fin["factual"]) / sd
                            mr[lev] = dict(
                                effect_rel=float(np.sqrt(((e_hat - e) ** 2).sum() / ((e ** 2).sum() + 1e-12)))
                                if np.all(np.isfinite(e_hat)) else None,
                                state_err=float(np.sqrt(np.mean(((fin[lev] - roll_true[lev][-1]) / sd) ** 2)))
                                if np.all(np.isfinite(fin[lev])) else None)
                        mr["factual_state_err"] = (float(np.sqrt(np.mean(((fin["factual"] - roll_true["factual"][-1]) / sd) ** 2)))
                                                   if np.all(np.isfinite(fin["factual"])) else None)
                        r["multi"] = mr
                    r["secs"] = time.time() - tic
                    out["results"].append(r)
                    print(f"[{args.system} s{seed} t={t}] {strategy:15s} {model:8s} fact={r['factual_err']:.4f} "
                          f"effect_rel(0.3)={r['0.3']['effect_rel']:.3f} rho(all)={r['all']['rank_rho']:.2f} "
                          f"({r['secs']:.1f}s)", flush=True)
            Path(args.out).write_text(json.dumps(out, indent=1))
        out["seeds"][str(seed)]["skipped_clipped_states"] = int(skipped)
        Path(args.out).write_text(json.dumps(out, indent=1))
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--system", default="pendulum", choices=["pendulum"] + list(ENVS))
    p.add_argument("--seed_ids", nargs="+", type=int, default=[0])
    p.add_argument("--models", nargs="+", default=["tabpfn", "dynapfn", "locallin", "mlp"])
    p.add_argument("--H", type=int, default=100)
    p.add_argument("--K", type=int, default=6, help="counterfactual actions per level")
    p.add_argument("--n_states", type=int, default=20)
    p.add_argument("--n_roll_states", type=int, default=5)
    p.add_argument("--h_multi", type=int, default=10)
    p.add_argument("--t_min", type=int, default=110)
    p.add_argument("--multi_arms", nargs="+", default=["tabpfn:retrieval", "tabpfn:retrieval_div", "tabpfn:recent",
                   "tabpfn:full", "dynapfn:retrieval", "locallin:retrieval", "mlp:trained"],
                   help="model:strategy pairs that also get the multi-step counterfactual rollouts")
    p.add_argument("--explore_frac", type=float, default=0.0)
    p.add_argument("--gain", type=float, default=1.0, help="pendulum data policy feedback gain")
    p.add_argument("--sigma", type=float, default=0.1, help="pendulum data policy exploration noise")
    p.add_argument("--n_train", type=int, default=None, help="default: 10 (D4RL) / 4 (pendulum)")
    p.add_argument("--T_train", type=int, default=1000)
    p.add_argument("--T_test", type=int, default=1000)
    # D4RL: same values as the main study (tasks_d4rl.txt) so seed k uses the same pool / test episode
    p.add_argument("--t0_min", type=int, default=100)
    p.add_argument("--horizon", type=int, default=100)
    p.add_argument("--full_cap", type=int, default=5000)
    p.add_argument("--data_dir", default="/scratch/naa9497/icwm/data/d4rl")
    p.add_argument("--tabpfn_version", default="v3.5")
    p.add_argument("--out", default="cf.json")
    a = p.parse_args()
    if a.n_train is None:
        a.n_train = 10 if a.system in ENVS else 4
    run(a)


if __name__ == "__main__":
    main()
